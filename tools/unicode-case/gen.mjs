// Writes packages/core/src/String/CaseData.fl: the case mapping of the
// default Unicode rules as Node (whose ICU the JS target uses) computes it,
// for the Flick bodies of `String.to_upper` and `String.to_lower`.
// Run from the repository root: `node tools/unicode-case/gen.mjs`; it
// formats the file with `flick fmt` of FLICK_BIN, target/debug/flick by default.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const out = "packages/core/src/String/CaseData.fl";
const cps = [];
for (let cp = 0; cp <= 0x10ffff; cp++) if (cp < 0xd800 || cp > 0xdfff) cps.push(cp);

// a mapping: one code point to one, by runs of a delta and a step; and the
// code points it maps to more than one
const mapping = (f) => {
  const simple = [];
  const special = [];
  for (const cp of cps) {
    const c = String.fromCodePoint(cp);
    const m = f(c);
    if (m === c) continue;
    const target = Array.from(m, (x) => x.codePointAt(0));
    if (target.length === 1) simple.push([cp, target[0] - cp]);
    else special.push([cp, m]);
  }
  const mapped = new Map(simple);
  const runs = [];
  let i = 0;
  while (i < simple.length) {
    const [lo, delta] = simple[i];
    // the longer of a run of step 1 and one of step 2 whose gaps map nothing
    let one = i;
    while (one + 1 < simple.length && simple[one + 1][0] === simple[one][0] + 1 && simple[one + 1][1] === delta) one++;
    let two = i;
    while (two + 1 < simple.length && simple[two + 1][0] === simple[two][0] + 2 && simple[two + 1][1] === delta && !mapped.has(simple[two][0] + 1)) two++;
    const [end, step] = two - i > one - i ? [two, 2] : [one, 1];
    runs.push([lo, simple[end][0], delta, step]);
    i = end + 1;
  }
  return { runs, special };
};

const ranges = (property) => {
  const re = new RegExp(`^\\p{${property}}$`, "u");
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const has = cp < 0x110000 && re.test(String.fromCodePoint(cp));
    if (has && start < 0) start = cp;
    if (!has && start >= 0) {
      out.push([start, cp - 1]);
      start = -1;
    }
  }
  return out;
};

const ints = (rows) => rows.flat().join(", ");
const wrap = (text) => {
  const lines = [];
  let line = "  ";
  for (const part of text.split(", ")) {
    if (line.length + part.length + 2 > 90) {
      lines.push(line.trimEnd());
      line = "  ";
    }
    line += `${part}, `;
  }
  lines.push(line.trimEnd().replace(/,$/, ""));
  return lines.join("\n");
};
const specials = (rows) => rows.map(([cp, m]) => `  (${cp}, ${JSON.stringify(m)})`).join(",\n");

const upper = mapping((c) => c.toUpperCase());
const lower = mapping((c) => c.toLowerCase());
const text = `// Generated by tools/unicode-case/gen.mjs from Node ${process.version}: do not edit.
/// The case mapping of the default Unicode rules, as JS's \`toUpperCase\`
/// and \`toLowerCase\` compute it: runs of \`[lo, hi, delta, step]\` that map
/// one code point to one, the code points that map to more, and the ranges
/// \`[lo, hi]\` of \`Cased\` and \`Case_Ignorable\` that final sigma reads.
private module String.CaseData exposing (upper_runs, upper_special, lower_runs, lower_special, cased, ignorable)

upper_runs : List Int
let upper_runs = [
${wrap(ints(upper.runs))},
]

upper_special : List (Int, String)
let upper_special = [
${specials(upper.special)},
]

lower_runs : List Int
let lower_runs = [
${wrap(ints(lower.runs))},
]

lower_special : List (Int, String)
let lower_special = [
${specials(lower.special)},
]

cased : List Int
let cased = [
${wrap(ints(ranges("Cased")))},
]

ignorable : List Int
let ignorable = [
${wrap(ints(ranges("Case_Ignorable")))},
]
`;
writeFileSync(out, text);
const fmt = spawnSync(process.env.FLICK_BIN ?? "target/debug/flick", ["fmt", out], { stdio: "inherit" });
if (fmt.status !== 0) throw new Error(`flick fmt ${out} failed`);
console.log(`${out}: ${text.length} bytes; ${upper.runs.length} upper and ${lower.runs.length} lower runs, ${upper.special.length} and ${lower.special.length} specials`);
