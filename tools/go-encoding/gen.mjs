const run = (parse) => (input) => {
  try {
    return JSON.stringify(parse(input));
  } catch (e) {
    return String(e);
  }
};
const write = (name, parse, inputs) =>
  writeFileSync(
    `runtime-go/flickrt/testdata/${name}.txt`,
    `${inputs.map((s) => `${JSON.stringify(s)}\t${run(parse)(s)}`).join("\n")}\n`,
  );
write("ini", Ini.parse, ini);
write("toml", Toml.parse, toml);
write("yaml", Yaml.parse, yaml);
