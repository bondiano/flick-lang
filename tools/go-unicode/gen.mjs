// Writes runtime-go/flickrt/unicode_tables.go: the Unicode data the go
// target's String functions need, as Node (whose ICU the JS target uses)
// computes it, so normalization and case mapping agree on both targets.
// Run from the repository root: `node tools/go-unicode/gen.mjs`.
import { writeFileSync } from "node:fs";

const out = "runtime-go/flickrt/unicode_tables.go";
const hex = (cp) => cp.toString(16);
const cps = (s) => Array.from(s, (c) => c.codePointAt(0));
const isHangul = (cp) => cp >= 0xac00 && cp <= 0xd7a3;
const chars = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  chars.push(cp);
}

// full decompositions of the code points they change; Hangul is algorithmic
const decompositions = (form) =>
  chars
    .filter((cp) => !isHangul(cp))
    .map((cp) => [cp, String.fromCodePoint(cp).normalize(form)])
    .filter(([cp, d]) => d !== String.fromCodePoint(cp))
    .map(([cp, d]) => `${hex(cp)}=${cps(d).map(hex).join(" ")}`)
    .join(";");

// primary composites: a character NFC gives back from its decomposition,
// by the pair it composes from
const composites = chars
  .filter((cp) => !isHangul(cp))
  .flatMap((cp) => {
    const c = String.fromCodePoint(cp);
    const d = cps(c.normalize("NFD"));
    if (d.length < 2 || d.map((x) => String.fromCodePoint(x)).join("").normalize("NFC") !== c) return [];
    const last = d[d.length - 1];
    const first = cps(String.fromCodePoint(...d.slice(0, -1)).normalize("NFC"));
    return first.length === 1 ? [`${hex(first[0])} ${hex(last)}=${hex(cp)}`] : [];
  })
  .join(";");

// combining classes, as ranks: a nonstarter moves before U+0345 (class
// 240) or after U+0334 (class 1); ranks keep the order NFD sorts them in
const reorders = (a, b) => (a + b).normalize("NFD") === b + a;
const nonstarters = chars
  .filter((cp) => String.fromCodePoint(cp).normalize("NFD") === String.fromCodePoint(cp))
  .map((cp) => String.fromCodePoint(cp))
  .filter((c) => reorders("ͅ", c) || reorders(c, "̴") || c === "ͅ" || c === "̴");
nonstarters.sort((a, b) => (reorders(a, b) ? 1 : reorders(b, a) ? -1 : 0));
let rank = 0;
const classes = nonstarters
  .map((c, i) => {
    if (i === 0 || reorders(c, nonstarters[i - 1]) || reorders(nonstarters[i - 1], c)) rank++;
    return `${hex(c.codePointAt(0))}=${rank}`;
  })
  .join(";");

// full case mappings of the code points they change
const mapping = (f) =>
  chars
    .map((cp) => [cp, f(String.fromCodePoint(cp))])
    .filter(([cp, m]) => m !== String.fromCodePoint(cp))
    .map(([cp, m]) => `${hex(cp)}=${cps(m).map(hex).join(" ")}`)
    .join(";");

const go = `// Code generated by tools/go-unicode/gen.mjs; DO NOT EDIT.

package flickrt

// Unicode ${process.versions.unicode}, as Node ${process.versions.node} (ICU ${process.versions.icu}) computes it.
const (
	nfdData       = "${decompositions("NFD")}"
	nfkdData      = "${decompositions("NFKD")}"
	compositeData = "${composites}"
	classData     = "${classes}"
	upperData     = "${mapping((s) => s.toUpperCase())}"
	lowerData     = "${mapping((s) => s.toLowerCase())}"
)
`;
writeFileSync(out, go);
console.log(`${out}: ${go.length} bytes, ${nonstarters.length} nonstarters in ${rank} classes`);
