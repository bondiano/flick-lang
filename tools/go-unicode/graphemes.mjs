// Writes runtime-go/flickrt/grapheme_tables.go: what Effect's
// `CliOutput.displayWidth` asks Node, so that both targets measure text
// alike:
// - the Grapheme_Cluster_Break class of each code point, with
//   Extended_Pictographic and Indic_Conjunct_Break, for UAX #29 as
//   `Intl.Segmenter` splits graphemes. The classes `\p{}` does not name
//   are found by how the segmenter treats each code point among others;
// - `[\p{Mark}\p{Control}\p{Default_Ignorable_Code_Point}]` and
//   `\p{Emoji_Presentation}`.
// It also writes runtime-go/flickrt/testdata/graphemes.txt, segments and
// widths of a corpus as Intl.Segmenter and Effect give them.
// Run from the repository root: `node tools/go-unicode/graphemes.mjs`.
import { writeFileSync } from "node:fs";
import { displayWidth } from "../../packages/effect-ts/node_modules/effect/dist/cli/CliOutput.js";

const out = "runtime-go/flickrt/grapheme_tables.go";
const corpusOut = "runtime-go/flickrt/testdata/graphemes.txt";
const hex = (cp) => cp.toString(16);
const segmenter = new Intl.Segmenter(undefined, { granularity: "grapheme" });
const segments = (s) => Array.from(segmenter.segment(s), (x) => x.segment);
const one = (s) => segments(s).length === 1;

// the classes, as grapheme.go numbers them
const CLASSES = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "RI", "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT"];
const C = Object.fromEntries(CLASSES.map((c, i) => [c, i]));
const EXT_PICT = 16, CONSONANT = 32, LINKER = 64, INCB_EXTEND = 96;

const RI = /^\p{Regional_Indicator}$/u, PICT = /^\p{Extended_Pictographic}$/u;
const EMOJI = "\u{1F600}", VIRAMA = "\u094D", KA = "क";
const classOf = (c) => {
  const cp = c.codePointAt(0);
  if (cp === 0x0d) return C.CR;
  if (cp === 0x0a) return C.LF;
  if (cp === 0x200d) return C.ZWJ;
  if (RI.test(c)) return C.RI;
  if (!one(c + "\u0300")) return C.Control; // only controls break before an Extend
  if (one("a" + c)) return one(EMOJI + c + "\u200D" + EMOJI) ? C.Extend : C.SpacingMark;
  if (one(c + "a")) return C.Prepend;
  if (one(c + "가")) return C.L; // L × LV
  if (one("가" + c)) return one("각" + c) ? C.T : C.V; // LV × (V|T), LVT × T
  if (one(c + "\u1161")) return C.LV; // LV × V
  if (one(c + "\u11A8")) return C.LVT; // LVT × T
  return C.Other;
};
const propertiesOf = (cp) => {
  const c = String.fromCodePoint(cp);
  const cls = classOf(c);
  let p = cls | (PICT.test(c) ? EXT_PICT : 0);
  if (one(c + VIRAMA + KA)) p |= CONSONANT;
  else if (cls === C.Extend && one(KA + c + KA)) p |= LINKER;
  else if ((cls === C.Extend || cls === C.ZWJ) && one(KA + c + VIRAMA + KA)) p |= INCB_EXTEND;
  return p;
};

// runs of code points of one value, `lo-hi=value` or `cp=value` in hex,
// without the runs of 0 (or false)
const runs = (valueOf) => {
  const entries = [];
  let start = 0, value = valueOf(0);
  for (let cp = 1; cp <= 0x110000; cp++) {
    const v = cp === 0x110000 ? -1 : cp >= 0xd800 && cp <= 0xdfff ? value : valueOf(cp);
    if (v === value) continue;
    if (value) entries.push(`${start === cp - 1 ? hex(start) : `${hex(start)}-${hex(cp - 1)}`}=${hex(Number(value))}`);
    start = cp;
    value = v;
  }
  return entries.join(";");
};
const property = (re) => (cp) => re.test(String.fromCodePoint(cp));

const properties = new Map();
const graphemeData = runs((cp) => {
  const p = propertiesOf(cp);
  if (!properties.has(p)) properties.set(p, cp);
  return p;
});
const zeroWidthData = runs(property(/^[\p{Mark}\p{Control}\p{Default_Ignorable_Code_Point}]$/u));
const emojiData = runs(property(/^\p{Emoji_Presentation}$/u));

const go = `// Code generated by tools/go-unicode/graphemes.mjs; DO NOT EDIT.

package flickrt

// Unicode ${process.versions.unicode}, as Node ${process.versions.node} (ICU ${process.versions.icu}) computes it.
const (
	// graphemeData is the Grapheme_Cluster_Break class of each code point (grapheme.go's
	// numbering), plus ${EXT_PICT} for Extended_Pictographic and ${CONSONANT}, ${LINKER} or ${INCB_EXTEND} for an
	// Indic_Conjunct_Break of Consonant, Linker or Extend: \`lo-hi=value\` or \`cp=value\` in hex.
	graphemeData = "${graphemeData}"
	// zeroWidthData is [\\p{Mark}\\p{Control}\\p{Default_Ignorable_Code_Point}], emojiData
	// \\p{Emoji_Presentation}, as graphemeData.
	zeroWidthData = "${zeroWidthData}"
	emojiData     = "${emojiData}"
)
`;
writeFileSync(out, go);
console.log(`${out}: ${go.length} bytes, ${properties.size} kinds of code point`);

// The corpus: a code point of every kind, after every other, then random
// strings of them (seeded), and texts Effect's docs and help measure.
const samples = [...properties.values(), 0x41, 0x1f1e6, 0x1f1fa, 0x1f3fd, 0xfe0f, 0x20e3, 0x1100, 0x1161, 0x11a8];
let seed = 17;
const random = (n) => {
  seed = (seed * 1103515245 + 12345) % 2147483648;
  return seed % n;
};
const texts = [
  "file", "ファイル", "é", "1\uFE0F\u20E3", "\u001B[1mbold\u001B[0m", "👍🏽", "👨\u200D👩\u200D👧\u200D👦", "🇺🇦🇺", "क\u094Dष\u093F", "क\u094D\u200Dष", "한국어", "\u1100\u1161\u11A8",
  "e\u0301\u0302", "กำ", "क\u093F", "\u0600١", "a\r\nb", "\u00AD", "🏳\uFE0F\u200D🌈", "©", "©\uFE0F", "a\u200Db", "\u{1F9D1}\u{1F3FB}\u200D\u{1F4BB}",
  ...samples.flatMap((a) => samples.map((b) => String.fromCodePoint(a, b))),
  ...Array.from({ length: 3000 }, () => String.fromCodePoint(...Array.from({ length: 2 + random(5) }, () => samples[random(samples.length)]))),
];
const cps = (s) => Array.from(s, (c) => hex(c.codePointAt(0))).join(" ");
const lines = texts.map((t) => `${segments(t).map(cps).join(" / ")} | ${displayWidth(t)}`);
writeFileSync(corpusOut, `# segments, apart by "/", as code points | displayWidth\n${lines.join("\n")}\n`);
console.log(`${corpusOut}: ${lines.length} texts`);
