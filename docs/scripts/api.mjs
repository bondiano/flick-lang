// The site's API is flick doc Markdown, not a second declaration model.
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = fileURLToPath(new URL("../../", import.meta.url));

/** Stable routes for both handwritten pages and generated API Markdown. */
export const contentId = ({ entry, data }) => String(data.slug ?? entry
  .replace(/^(?:src\/content\/docs|\.generated)\//, "")
  .replace(/\.(?:md|mdx|markdown|mdown|mkdn|mkd|mdwn)$/, "")
  .toLowerCase().replace(/\/index$/, ""));

/** Add site frontmatter and rewrite only CLI module-page links, leaving prose alone. */
export function apiPages(pages) {
  const names = [...pages.keys()].filter((name) => name !== "index.md").sort();
  const routes = new Map(names.map((name) => [name, `${name.slice(0, -3).toLowerCase()}/`]));
  const output = new Map();
  for (const locale of ["", "ru/"]) {
    const title = locale ? "API стандартной библиотеки" : "Standard library API";
    const intro = locale
      ? "Сгенерировано командой `flick doc --std` из публичного интерфейса компилятора и doc comments. Сигнатуры и комментарии одинаковы для обоих языков."
      : "Generated by `flick doc --std` from the compiler's public interface and doc comments. Signatures and comments are shared between locales.";
    const index = `---\ntitle: ${JSON.stringify(title)}\n---\n\n${intro}\n\n${names.map((name) => `- [${name.slice(0, -3)}](./${routes.get(name)})`).join("\n")}\n`;
    output.set(`${locale}api/index.md`, index);
    for (const name of names) {
      const module = name.slice(0, -3);
      const body = pages.get(name).replace(/^# [^\n]+\n/, "").replace(/\]\(([^)]+\.md)(#[^)]*)?\)/g, (match, file, fragment = "") => routes.has(file) ? `](../${routes.get(file)}${fragment})` : match);
      output.set(`${locale}api/${module.toLowerCase()}.md`, `---\ntitle: ${JSON.stringify(module)}\n---\n${body}`);
    }
  }
  return output;
}

export function generateApi(binary = process.env.FLICK_BIN ?? path.join(repo, "target/debug/flick")) {
  const docs = path.join(repo, "docs");
  const stage = mkdtempSync(path.join(docs, ".api-stage-"));
  try {
    const raw = path.join(stage, "raw");
    const revision = execFileSync("git", ["rev-parse", "HEAD"], { cwd: repo, encoding: "utf8" }).trim();
    execFileSync(binary, ["doc", "--std", "--check-examples", "--out-dir", raw, "--source-base-url", `https://github.com/bondiano/flick-lang/blob/${revision}`], { cwd: repo, stdio: "inherit", env: { ...process.env, FLICK_STD_PATH: path.join(repo, "packages/std") } });
    const pages = new Map(readdirSync(raw).filter((name) => name.endsWith(".md")).map((name) => [name, readFileSync(path.join(raw, name), "utf8")]));
    if (pages.size <= 1) throw new Error("flick doc produced no standard library modules");
    const ready = path.join(stage, "ready");
    for (const [name, text] of apiPages(pages)) {
      const file = path.join(ready, name);
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, text);
    }
    // Replace only our generated tree, after the CLI has succeeded.
    const destination = path.join(docs, ".generated");
    rmSync(destination, { recursive: true, force: true });
    renameSync(ready, destination);
  } finally {
    rmSync(stage, { recursive: true, force: true });
  }
}

if (import.meta.main) generateApi();
