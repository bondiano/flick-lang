pub(super) fn table() -> ValueAbi {
    ValueAbi {
        abi: Abi {
            name: ABI_NAME.into(),
            version: ABI_VERSION.into(),
        },
        opaque_type: "unknown".into(),
        catch_error_type: "unknown".into(),
        catch_lang_item: Some("js_value".into()),
        entries: JS_ENTRIES
            .iter()
            .map(
                |&(key, flick_type, host_type, conversion, direction, notes)| ValueAbiEntry {
                    key: key.into(),
                    flick_type: flick_type.into(),
                    host_type: host_type.into(),
                    conversion,
                    direction,
                    notes: notes.into(),
                },
            )
            .collect(),
        unsupported: vec![],
        fallback_reason: "type is outside the `flick.javascript-ffi` value ABI table".into(),
        admits_copied_data: true,
    }
}
