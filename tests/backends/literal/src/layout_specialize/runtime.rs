//! Foreign runtime bindings and JS runtime prelude for `layout-specialize`.

use flick_ir::Foreign;

pub(super) fn emit_foreign(module: &str, f: &Foreign) -> String {
    if let Some((spec, exp)) = f.binding.module_export() {
        match (spec, exp) {
            ("flick:rt", "stdoutLine") => return "((s) => { console.log(s); })".to_owned(),
            ("flick:rt", "show") => return "$show".to_owned(),
            ("flick:rt", "listLength") => return "((xs) => xs.length | 0)".to_owned(),
            ("flick:rt", "listReverse") => return "((xs) => [...xs].reverse())".to_owned(),
            ("flick:rt", "listMap") => {
                return "((fn) => (xs) => xs.map((x) => fn(x)))".to_owned();
            }
            ("flick:rt", "listFoldLeft") => {
                return "((fn) => (init) => (xs) => xs.reduce((a, x) => fn(a)(x), init))"
                    .to_owned();
            }
            ("flick:rt", "listGet") => {
                return "((i) => (xs) => (i >= 0 && i < xs.length) ? { _tag: \"Prelude.Option.Some\", _f: [xs[i]], _o: 1 } : { _tag: \"Prelude.Option.None\", _f: [], _o: 0 })".to_owned();
            }
            ("flick:rt", "listRange") => {
                return "((a) => (b) => { const r = []; for (let i = a; i < b; i++) r.push(i); return r; })".to_owned();
            }
            ("flick:rt", "stringLength") => return "((s) => s.length | 0)".to_owned(),
            ("flick:rt", "stringIndexOf" | "indexOf") => {
                return "((needle) => (hay) => { const i = hay.indexOf(needle); return i >= 0 ? { _tag: \"Prelude.Option.Some\", _f: [i], _o: 1 } : { _tag: \"Prelude.Option.None\", _f: [], _o: 0 }; })".to_owned();
            }
            ("flick:rt", "stringContains") => {
                return "((needle) => (hay) => hay.includes(needle))".to_owned();
            }
            ("flick:rt", "equals" | "primEquals") => {
                return "((a) => (b) => $eq(a, b))".to_owned();
            }
            ("flick:rt", "compare" | "primCompare") => {
                return "((a) => (b) => a < b ? { _tag: \"Prelude.Ordering.LT\", _f: [], _o: 0 } : a > b ? { _tag: \"Prelude.Ordering.GT\", _f: [], _o: 0 } : { _tag: \"Prelude.Ordering.EQ\", _f: [], _o: 0 })".to_owned();
            }
            _ => {}
        }
    }
    match (module, f.name.as_str()) {
        ("Platform", "stdout_line") => "((s) => { console.log(s); })".to_owned(),
        ("List" | "List.Core", "length") => "((xs) => xs.length | 0)".to_owned(),
        ("List" | "List.Core", "reverse") => "((xs) => [...xs].reverse())".to_owned(),
        ("List" | "List.Core", "map") => "((fn) => (xs) => xs.map((x) => fn(x)))".to_owned(),
        ("Prelude", "show" | "show_prim" | "show_value") => "$show".to_owned(),
        ("Instances", "index_of") => {
            "((needle) => (hay) => { const i = hay.indexOf(needle); return i >= 0 ? { _tag: \"Prelude.Option.Some\", _f: [i], _o: 1 } : { _tag: \"Prelude.Option.None\", _f: [], _o: 0 }; })".to_owned()
        }
        _ => {
            if let flick_ir::Binding::Global { name } = &f.binding {
                if f.arity == 1 {
                    format!("((a0) => ({name})(a0))")
                } else {
                    format!("({name})")
                }
            } else {
                "((x) => x)".to_owned()
            }
        }
    }
}

