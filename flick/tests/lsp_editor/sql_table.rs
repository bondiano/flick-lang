use std::path::PathBuf;

use super::*;

const SOURCE: &str = r#"module App.Ledger exposing (Accounts, label, same, user_id)

import Sql exposing (Pg, plugin sql)
import BigDecimal exposing (BigDecimal)
import App.Ids as Ids exposing (UserId(..))

user_id : PureCodec BigInt UserId
let user_id = Sql.codec (fun n -> Ok (UserId n)) (fun (UserId n) -> n)

label : PureCodec String String
let label = Sql.codec (fun s -> Ok s) (fun s -> s)

type alias IdCodec = PureCodec BigInt UserId

hidden : PureCodec BigInt UserId
let hidden = Sql.codec (fun n -> Ok (UserId n)) (fun (UserId n) -> n)

aliased : IdCodec
let aliased = hidden

same : forall a. PureCodec a a
let same = Sql.codec (fun x -> Ok x) (fun x -> x)

sql table Accounts "accounts" {
  id : bigint primary key generated always as BigInt
  user_id : bigint not null as UserId via user_id
  balance : numeric not null default as BigDecimal
  name : text not null as String via label
}
"#;

const IDS: &str = "module App.Ids exposing (..)

import Sql exposing (plugin sql)

type UserId = UserId BigInt

user_id_codec : PureCodec BigInt UserId
let user_id_codec = Sql.codec (fun n -> Ok (UserId n)) (fun (UserId n) -> n)
";

fn open(name: &str) -> (Lsp, PathBuf) {
    let dir = project(
        name,
        &[
            ("flick.toml", LIB),
            ("src/App/Ids.fl", IDS),
            ("src/App/Ledger.fl", SOURCE),
        ],
    );
    let file = dir.join("src/App/Ledger.fl");
    let mut lsp = Lsp::start(&dir);
    lsp.notify("textDocument/didOpen", &json!({ "textDocument": { "uri": uri(&file), "languageId": "flick", "version": 1, "text": SOURCE } }));
    let diagnostics = lsp.diagnostics(&uri(&file));
    assert!(
        diagnostics.iter().all(|d| d["tags"] == json!([1])),
        "{diagnostics:?}"
    );
    (lsp, file)
}

#[test]
fn sql_table_hover() {
    let (mut lsp, file) = open("lsp_sql_table_hover");
    for (needle, offset, expected) in [
        (
            "table Accounts",
            1,
            "type alias Accounts = { id : BigInt; user_id : UserId; balance : BigDecimal; name : String }",
        ),
        (
            "table Accounts",
            1,
            "Accounts.table : Sql.Table \"accounts\"",
        ),
        ("table Accounts", 2, "Dialect: PostgreSQL"),
        ("Accounts \"", 1, "A row of the PostgreSQL table `accounts`"),
        (
            "\"accounts\"",
            2,
            "queries over `Accounts` read and write `accounts`",
        ),
        (
            "bigint primary",
            1,
            "PostgreSQL `bigint`: Flick value `BigInt`",
        ),
        ("numeric not", 1, "Flick value `BigDecimal`"),
        ("primary key", 9, "implies `not null`"),
        ("generated always", 12, "an insert or update cannot give it"),
        ("not null as UserId", 5, "its values are not in `Option`"),
        ("default as", 1, "an insert may leave the column out"),
        ("as UserId", 0, "The Flick type `UserId`"),
        ("via user_id", 1, "A `PureCodec BigInt UserId`"),
        ("user_id : bigint", 1, "user_id : UserId"),
    ] {
        let hover = lsp.request(
            "textDocument/hover",
            &json!({
                "textDocument": { "uri": uri(&file) },
                "position": position(SOURCE, SOURCE.find(needle).expect("occurs") + offset),
            }),
        );
        assert!(
            hover["result"]["contents"]["value"]
                .as_str()
                .is_some_and(|s| s.contains(expected)),
            "{needle}: {hover}"
        );
    }
    lsp.close();
}

#[test]
fn sql_table_completion() {
    let (mut lsp, file) = open("lsp_sql_table_completion");
    for (old, replacement, wanted, unwanted) in [
        (
            "balance : numeric not null default",
            "balance : nu",
            &["numeric", "text", "double precision"][..],
            &["not null", "user_id", "BigDecimal"][..],
        ),
        (
            "balance : numeric not null default",
            "balance : numeric not null d",
            &["default", "unique", "primary key", "as"],
            &["not null", "null", "numeric"],
        ),
        (
            "id : bigint primary key generated always",
            "id : bigint primary key g",
            &["generated always", "generated by default", "unique"],
            &["null", "primary key"],
        ),
        (
            "id : bigint primary key generated always",
            "id : bigint primary key generated always u",
            &["unique", "not null", "as"],
            &["default", "generated by default", "generated always"],
        ),
        // after `as` and `via` the names in scope, unfiltered by type
        (
            "as BigDecimal",
            "as Big",
            &["BigDecimal", "UserId", "String"],
            &["bigint"],
        ),
        (
            "via user_id",
            "via us",
            &["user_id", "hidden", "aliased"],
            &["bigint"],
        ),
        (
            "UserId via user_id",
            "UserId via ",
            &["user_id", "hidden", "aliased"],
            &["not null"],
        ),
        (
            "String via label",
            "String via ",
            &["label", "same"],
            &["not null"],
        ),
        (
            "default as BigDecimal",
            "default as ",
            &["BigDecimal", "UserId", "String"],
            &["bigint", "numeric"],
        ),
    ] {
        let text = SOURCE.replacen(old, replacement, 1);
        lsp.notify("textDocument/didChange", &json!({ "textDocument": { "uri": uri(&file), "version": 2 }, "contentChanges": [{ "text": text }] }));
        let completion = lsp.request("textDocument/completion", &json!({
            "textDocument": { "uri": uri(&file) },
            "position": position(&text, text.find(replacement).expect("occurs") + replacement.len()),
        }));
        let labels: Vec<&str> = completion["result"]
            .as_array()
            .expect("items")
            .iter()
            .filter_map(|i| i["label"].as_str())
            .collect();
        for w in wanted {
            assert!(labels.contains(w), "{replacement}: {w} in {labels:?}");
        }
        for u in unwanted {
            assert!(!labels.contains(u), "{replacement}: {u} in {labels:?}");
        }
    }
    lsp.close();
}
