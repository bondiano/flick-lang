/// The column type that `words` start with.
pub fn column_type(words: &[&str]) -> Option<&'static ColumnType> {
    TYPES.iter().find(|t| {
        let n = t.words.split(' ').count();
        words.len() >= n && words[..n].join(" ") == t.words
    })
}

