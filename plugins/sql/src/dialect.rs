//! The dialect `PostgreSQL` as a table reads it: the SQL types a column may have, with
//! how the runtime passes their values and the Flick type of a value
//! without a codec, and the attributes after the type.

/// A SQL type a column may have.
pub struct ColumnType {
    /// The words of the type, as a table writes them.
    pub words: &'static str,
    /// How the runtime passes and reads values of it.
    pub kind: &'static str,
    /// The Flick type of a value without a codec, as the column writes it.
    pub flick: &'static str,
    /// That type in full, as the checker shows it qualified.
    pub exact: &'static str,
}

const fn ty(words: &'static str, kind: &'static str, flick: &'static str) -> ColumnType {
    let exact = match flick.as_bytes() {
        b"BigDecimal" => "BigDecimal.BigDecimal",
        b"BigInt" => "Prelude.BigInt",
        b"Int" => "Prelude.Int",
        b"Float" => "Prelude.Float",
        b"Bool" => "Prelude.Bool",
        b"Json" => "Prelude.Json",
        _ => "Prelude.String",
    };
    ColumnType {
        words,
        kind,
        flick,
        exact,
    }
}

/// How documentation and the editor name the dialect.
pub const TITLE: &str = "PostgreSQL";

