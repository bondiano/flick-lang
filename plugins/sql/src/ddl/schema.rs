//! The schema a module's migrations build, applied in order: tables and
//! their columns, what an `INSERT` must give each, and why a statement does
//! not apply. The subset is what a schema's history needs: `create table`,
//! `create index`, `alter table` (add, drop, rename and alter a column,
//! rename the table), `drop table` and `drop index`.

use super::{Migration, Range, Statement, Word};

/// What an `INSERT` must give a column.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Write {
    Required,
    Defaulted,
    Generated,
}

impl Write {
    /// The index of `Sql.Column` it is.
    pub fn index(self) -> &'static str {
        match self {
            Write::Required => "Required",
            Write::Defaulted => "Defaulted",
            Write::Generated => "Generated",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Column {
    pub name: String,
    /// The words of its SQL type, `double precision`.
    pub ty: Vec<String>,
    pub range: Range,
    pub not_null: bool,
    /// A `default`, a `serial` type or `generated by default`.
    pub default: bool,
    /// `generated always`.
    pub generated: bool,
}

impl Column {
    /// What an `INSERT` must give it: a nullable column may be left out.
    pub fn write(&self) -> Write {
        if self.generated {
            Write::Generated
        } else if self.default || !self.not_null {
            Write::Defaulted
        } else {
            Write::Required
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Table {
    pub name: String,
    /// Its `create table` statement, and the name there.
    pub range: Range,
    pub at: Range,
    pub columns: Vec<Column>,
}

/// Why a statement does not apply; `unsupported` when it is outside the
/// subset rather than wrong.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Problem {
    pub range: Range,
    pub message: String,
    pub unsupported: bool,
}

/// The words that end a column's type and start a constraint.
const CONSTRAINTS: [&str; 10] = [
    "not",
    "null",
    "primary",
    "unique",
    "default",
    "generated",
    "references",
    "check",
    "constraint",
    "collate",
];

#[derive(Default)]
pub(super) struct Schema {
    pub(super) tables: Vec<Table>,
    pub(super) indexes: Vec<String>,
    problems: Vec<Problem>,
}

/// The tables after every migration, and the problems found on the way.
pub fn schema(migrations: &[Migration]) -> (Vec<Table>, Vec<Problem>) {
    let mut s = Schema::default();
    let mut last: Option<i64> = None;
    for m in migrations {
        match (m.version, last) {
            (None, _) => s.problem(m.range, "a migration's version is a whole number".into()),
            (Some(v), Some(l)) if v <= l => s.problem(
                m.range,
                format!("migration {v} comes after {l}: versions increase in the order written"),
            ),
            (Some(v), _) if v < 1 => {
                s.problem(m.range, "a migration's version is 1 or more".into());
            }
            _ => {}
        }
        last = m.version.or(last);
        for statement in &m.statements {
            s.statement(statement);
        }
    }
    (s.tables, s.problems)
}

/// An identifier as SQL folds it, in lower case.
pub(super) fn ident(w: &Word) -> String {
    w.lower()
}

/// The words between the parenthesis at `open` and its match, and the
/// position after it.
fn group(words: &[Word], open: usize) -> Option<(&[Word], usize)> {
    let mut depth = 0;
    for (i, w) in words.iter().enumerate().skip(open) {
        match w.text.as_str() {
            "(" => depth += 1,
            ")" if depth == 1 => return Some((&words[open + 1..i], i + 1)),
            ")" => depth -= 1,
            _ => {}
        }
    }
    None
}

/// The items of a list at depth 0, split at its commas.
pub(super) fn items(words: &[Word]) -> Vec<&[Word]> {
    let mut out = Vec::new();
    let (mut depth, mut start) = (0, 0);
    for (i, w) in words.iter().enumerate() {
        match w.text.as_str() {
            "(" => depth += 1,
            ")" => depth -= 1,
            "," if depth == 0 => {
                out.push(&words[start..i]);
                start = i + 1;
            }
            _ => {}
        }
    }
    out.push(&words[start..]);
    out.into_iter().filter(|i| !i.is_empty()).collect()
}

pub(super) fn lower(words: &[Word]) -> Vec<String> {
    words.iter().map(Word::lower).collect()
}

pub(super) fn span(words: &[Word]) -> Range {
    let start = words.first().map_or(0, |w| w.range.0);
    (start, words.last().map_or(start, |w| w.range.1))
}

impl Schema {
    pub(super) fn problem(&mut self, range: Range, message: String) {
        self.problems.push(Problem {
            range,
            message,
            unsupported: false,
        });
    }

    pub(super) fn unsupported(&mut self, words: &[Word], what: &str) {
        self.problems.push(Problem {
            range: span(words),
            message: format!("{what} is outside the DDL a migration may hold: `create table`, `create index`, `alter table`, `drop table`, `drop index`"),
            unsupported: true,
        });
    }

    pub(super) fn table(&mut self, name: &str) -> Option<&mut Table> {
        self.tables.iter_mut().find(|t| t.name == name)
    }

    /// The table `w` names, or a problem.
    pub(super) fn known(&mut self, w: &Word) -> Option<usize> {
        let name = ident(w);
        let found = self.tables.iter().position(|t| t.name == name);
        if found.is_none() {
            self.problem(w.range, format!("no table `{name}` here"));
        }
        found
    }

    fn statement(&mut self, statement: &Statement) {
        let words = &statement.words;
        let lowered = lower(words);
        let at = |i: usize| lowered.get(i).map_or("", String::as_str);
        match (at(0), at(1)) {
            ("create", "table") => self.create_table(words),
            ("create", "index" | "unique") => self.create_index(words),
            ("alter", "table") => self.alter_table(words),
            ("drop", "table") => self.drop_table(words),
            ("drop", "index") => self.drop_index(words),
            _ => self.unsupported(
                words,
                &format!(
                    "`{}`",
                    lowered
                        .iter()
                        .take(2)
                        .cloned()
                        .collect::<Vec<_>>()
                        .join(" ")
                ),
            ),
        }
    }

    fn create_table(&mut self, words: &[Word]) {
        let mut i = 2;
        if lower(&words[i..words.len().min(i + 3)]) == ["if", "not", "exists"] {
            i += 3;
        }
        let Some(name) = words.get(i) else {
            return self.unsupported(words, "`create table` without a name");
        };
        let table = ident(name);
        if self.tables.iter().any(|t| t.name == table) {
            return self.problem(name.range, format!("the table `{table}` exists already"));
        }
        let Some((body, _)) = (words.get(i + 1).is_some_and(|w| w.text == "("))
            .then(|| group(words, i + 1))
            .flatten()
        else {
            return self.unsupported(words, "`create table` without its columns");
        };
        // a table may refer to itself
        self.tables.push(Table {
            name: table.clone(),
            range: span(words),
            at: name.range,
            columns: Vec::new(),
        });
        let mut keys = Vec::new();
        for item in items(body) {
            let head = lower(&item[..item.len().min(2)]);
            match head.first().map(String::as_str) {
                Some("primary") if head.get(1).map(String::as_str) == Some("key") => {
                    if let Some((cols, _)) = group(item, 2) {
                        keys.extend(items(cols).iter().filter_map(|c| c.first()).cloned());
                    }
                }
                Some("unique" | "check" | "exclude") => {}
                Some("foreign") => self.foreign(&table, item),
                Some("constraint") => self.unsupported(item, "a named constraint"),
                _ => {
                    if let Some(column) = self.column(&table, item) {
                        self.add_column(&table, column, item);
                    }
                }
            }
        }
        for key in keys {
            let name = ident(&key);
            match self
                .table(&table)
                .and_then(|t| t.columns.iter_mut().find(|c| c.name == name))
            {
                Some(c) => c.not_null = true,
                None => self.problem(key.range, format!("no column `{name}` in `{table}`")),
            }
        }
    }

    pub(super) fn add_column(&mut self, table: &str, column: Column, item: &[Word]) {
        let Some(t) = self.table(table) else { return };
        if t.columns.iter().any(|c| c.name == column.name) {
            let message = format!("the table `{table}` has a column `{}` already", column.name);
            return self.problem(span(item), message);
        }
        t.columns.push(column);
    }

    /// `foreign key (a) references t (b)`.
    fn foreign(&mut self, table: &str, item: &[Word]) {
        let Some((_, after)) = group(item, 2) else {
            return self.unsupported(item, "a foreign key without its columns");
        };
        if item.get(after).map(Word::lower).as_deref() == Some("references") {
            self.reference(table, &item[after + 1..]);
        }
    }

    /// The table and column after `references`, which exist.
    fn reference(&mut self, table: &str, rest: &[Word]) {
        let Some(target) = rest.first() else { return };
        let name = ident(target);
        let Some(columns) = self
            .tables
            .iter()
            .find(|t| t.name == name || name == table)
            .map(|t| t.columns.iter().map(|c| c.name.clone()).collect::<Vec<_>>())
        else {
            return self.problem(target.range, format!("no table `{name}` to refer to"));
        };
        if rest.get(1).is_some_and(|w| w.text == "(")
            && let Some((cols, _)) = group(rest, 1)
        {
            for c in items(cols).iter().filter_map(|c| c.first()) {
                if !columns.contains(&ident(c)) {
                    self.problem(c.range, format!("no column `{}` in `{name}`", ident(c)));
                }
            }
        }
    }

    /// A column definition: its name, type words and constraints.
    pub(super) fn column(&mut self, table: &str, item: &[Word]) -> Option<Column> {
        let name = ident(item.first()?);
        let lowered = lower(item);
        let end = lowered
            .iter()
            .skip(1)
            .position(|w| CONSTRAINTS.contains(&w.as_str()))
            .map_or(item.len(), |p| p + 1);
        let ty: Vec<String> = lowered[1..end].to_vec();
        if ty.is_empty() {
            self.unsupported(item, "a column without a type");
            return None;
        }
        let mut column = Column {
            name,
            default: ty[0].ends_with("serial"),
            ty,
            range: span(item),
            not_null: false,
            generated: false,
        };
        let mut i = end;
        let word = |i: usize| lowered.get(i).map_or("", String::as_str);
        while i < item.len() {
            match (word(i), word(i + 1)) {
                ("not", "null") | ("primary", "key") => {
                    column.not_null = true;
                    i += 2;
                }
                ("null" | "unique", _) => i += 1,
                ("default", _) => {
                    column.default = true;
                    i += 1;
                    // the expression, up to the next constraint
                    let mut depth = 0;
                    while i < item.len() && (depth > 0 || !CONSTRAINTS.contains(&word(i))) {
                        depth += i32::from(word(i) == "(") - i32::from(word(i) == ")");
                        i += 1;
                    }
                }
                ("generated", "always") => {
                    column.generated = true;
                    i = Self::skip_generated(item, i + 2);
                }
                ("generated", "by") if word(i + 2) == "default" => {
                    column.default = true;
                    i = Self::skip_generated(item, i + 3);
                }
                ("references", _) => {
                    self.reference(table, &item[i + 1..]);
                    i += 2;
                    if word(i) == "(" {
                        i = group(item, i).map_or(item.len(), |(_, after)| after);
                    }
                    while matches!(word(i), "on") {
                        i += if matches!(word(i + 2), "set" | "no") {
                            4
                        } else {
                            3
                        };
                    }
                }
                ("check", _) => i = group(item, i + 1).map_or(item.len(), |(_, after)| after),
                ("collate", _) => i += 2,
                (other, _) => {
                    let what = format!("the column constraint `{other}`");
                    self.unsupported(&item[i..], &what);
                    return None;
                }
            }
        }
        Some(column)
    }

    /// After `generated always` or `generated by default`: `as identity` or
    /// `as (expression) stored`.
    fn skip_generated(item: &[Word], mut i: usize) -> usize {
        let word = |i: usize| item.get(i).map(Word::lower).unwrap_or_default();
        if word(i) == "as" {
            i += 1;
        }
        if word(i) == "identity" {
            return i + 1;
        }
        let after = group(item, i).map_or(item.len(), |(_, after)| after);
        after + usize::from(word(after) == "stored")
    }

    fn create_index(&mut self, words: &[Word]) {
        let lowered = lower(words);
        let Some(on) = lowered.iter().position(|w| w == "on") else {
            return self.unsupported(words, "an index without `on`");
        };
        let name = lowered[2..on]
            .iter()
            .rfind(|w| {
                !matches!(
                    w.as_str(),
                    "index" | "if" | "not" | "exists" | "concurrently"
                )
            })
            .cloned();
        if let Some(name) = name {
            if self.indexes.contains(&name) {
                return self.problem(span(words), format!("the index `{name}` exists already"));
            }
            self.indexes.push(name);
        }
        let Some(target) = words.get(on + 1) else {
            return;
        };
        let Some(t) = self.known(target) else { return };
        let columns: Vec<String> = self.tables[t]
            .columns
            .iter()
            .map(|c| c.name.clone())
            .collect();
        let open = (on + 2..words.len()).find(|&i| words[i].text == "(");
        if let Some((cols, _)) = open.and_then(|o| group(words, o)) {
            for c in items(cols).iter().filter_map(|c| c.first()) {
                if c.text != "(" && !columns.contains(&ident(c)) {
                    self.problem(
                        c.range,
                        format!("no column `{}` in `{}`", ident(c), self.tables[t].name),
                    );
                }
            }
        }
    }
}
