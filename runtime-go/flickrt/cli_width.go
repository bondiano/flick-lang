// `Cli.display_width`: the columns text takes in a terminal as Effect's
// `CliOutput.displayWidth` counts them, by grapheme: none for marks,
// controls and default-ignorable code points, two for emoji and wide East
// Asian characters. The tables of the emoji properties Go's unicode
// package lacks are Node's (`\p{Emoji_Presentation}`,
// `\p{Extended_Pictographic}`, `\p{Default_Ignorable_Code_Point}`).

var cliAnsi = regexp.MustCompile("\x1b\\[[0-9;]*m")

func cliWidth(text string) int {
	n := 0
	for _, g := range cliGraphemes(cliAnsi.ReplaceAllString(text, "")) {
		n += cliGraphemeWidth(g)
	}
	return n
}

func cliIn(table []rune, r rune) bool {
	lo, hi := 0, len(table)/2
	for lo < hi {
		mid := (lo + hi) / 2
		switch {
		case r < table[2*mid]:
			hi = mid
		case r > table[2*mid+1]:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}

func cliZeroWidth(r rune) bool {
	return unicode.Is(unicode.M, r) || unicode.Is(unicode.Cc, r) || cliIn(cliIgnorable, r)
}

func cliGraphemeWidth(g []rune) int {
	first := rune(-1)
	emoji := false
	for _, r := range g {
		if first < 0 && !cliZeroWidth(r) {
			first = r
		}
		emoji = emoji || r == 0xFE0F || cliIn(cliEmojiPresentation, r)
	}
	switch {
	case first < 0:
		return 0
	case emoji:
		return 2
	case cliFullWidth(first):
		return 2
	}
	return 1
}

func cliFullWidth(c rune) bool {
	if c < 0x1100 {
		return false
	}
	return c <= 0x115f || c == 0x2329 || c == 0x232a || c >= 0x2e80 && c <= 0x303e || c >= 0x3040 && c <= 0xa4cf ||
		c >= 0xac00 && c <= 0xd7a3 || c >= 0xf900 && c <= 0xfaff || c >= 0xfe10 && c <= 0xfe19 ||
		c >= 0xfe30 && c <= 0xfe6f || c >= 0xff00 && c <= 0xff60 || c >= 0xffe0 && c <= 0xffe6 ||
		c >= 0x1b000 && c <= 0x1b2ff || c >= 0x1f200 && c <= 0x1f251 || c >= 0x20000 && c <= 0x3fffd
}

// cliGraphemes splits text into extended grapheme clusters as Unicode's
// segmentation rules do for marks, joiners, emoji sequences, flags and
// Hangul syllables.
//
// shortcut: no prepended concatenation marks or Indic conjuncts, which Intl.Segmenter joins; add their rules if help text uses those scripts
func cliGraphemes(s string) [][]rune {
	var out [][]rune
	var cur []rune
	pictographic, regional := false, 0
	for len(s) > 0 {
		r, n := decode(s)
		s = s[n:]
		if len(cur) > 0 && cliBreaks(cur[len(cur)-1], r, pictographic, regional) {
			out, cur, pictographic, regional = append(out, cur), nil, false, 0
		}
		if len(cur) == 0 || !cliExtends(r) && r != 0x200D {
			pictographic = cliIn(cliPictographic, r)
		}
		if r >= 0x1F1E6 && r <= 0x1F1FF {
			regional++
		}
		cur = append(cur, r)
	}
	if len(cur) > 0 {
		out = append(out, cur)
	}
	return out
}

func cliControl(r rune) bool {
	return r == '\r' || r == '\n' || unicode.Is(unicode.Cc, r) || unicode.Is(unicode.Zl, r) ||
		unicode.Is(unicode.Zp, r) || unicode.Is(unicode.Cf, r) && r != 0x200C && r != 0x200D
}

func cliExtends(r rune) bool {
	return unicode.Is(unicode.M, r) || r == 0x200C || r >= 0x1F3FB && r <= 0x1F3FF ||
		unicode.Is(unicode.Other_Grapheme_Extend, r)
}

func cliHangul(r rune) string {
	switch {
	case r >= 0x1100 && r <= 0x115F || r >= 0xA960 && r <= 0xA97C:
		return "L"
	case r >= 0x1160 && r <= 0x11A7 || r >= 0xD7B0 && r <= 0xD7C6:
		return "V"
	case r >= 0x11A8 && r <= 0x11FF || r >= 0xD7CB && r <= 0xD7FB:
		return "T"
	case r >= 0xAC00 && r <= 0xD7A3 && (r-0xAC00)%28 == 0:
		return "LV"
	case r >= 0xAC00 && r <= 0xD7A3:
		return "LVT"
	}
	return ""
}

// cliBreaks tells whether a cluster ends between `prev` and `r`; the
// cluster so far started with a pictograph, and holds `regional`
// indicators.
func cliBreaks(prev, r rune, pictographic bool, regional int) bool {
	switch {
	case prev == '\r' && r == '\n':
		return false
	case cliControl(prev) || cliControl(r):
		return true
	}
	switch p, q := cliHangul(prev), cliHangul(r); {
	case p == "L" && (q == "L" || q == "V" || q == "LV" || q == "LVT"),
		(p == "LV" || p == "V") && (q == "V" || q == "T"),
		(p == "LVT" || p == "T") && q == "T":
		return false
	}
	switch {
	case cliExtends(r) || r == 0x200D:
		return false
	case prev == 0x200D && pictographic && cliIn(cliPictographic, r):
		return false
	case regional%2 == 1 && r >= 0x1F1E6 && r <= 0x1F1FF && prev >= 0x1F1E6 && prev <= 0x1F1FF:
		return false
	}
	return true
}

