//! Hover on a generated companion member such as `Page.url`: what the
//! compiler generated and what it is for; navigation still leads to the
//! owning type.

use std::fmt::Write;

use super::{Ide, documentation, tree};
use crate::source::FileId;
use crate::types::{Abi, EnumLit, Form, Ref, TypeDef, show_signature};

impl Ide<'_> {
    pub(super) fn companion_hover(
        &self,
        file: FileId,
        offset: u32,
    ) -> Option<(String, (u32, u32))> {
        let m = self.module(file)?;
        let (range, reference) = tree::innermost(m.typing.names.iter(), offset)?;
        let Ref::Value { module, name } = reference else {
            return None;
        };
        let (owner, member) = name.split_once('$')?;
        let token = tree::last_name(tree::find(&m.tree, range)?)?;
        if token.text(self.text(file)) != member || !(token.start <= offset && offset <= token.end)
        {
            return None;
        }
        let note = companion_note(member)?;
        let ty = m.typing.types.get(&range)?;
        let mut markdown = format!(
            "```flick\n{owner}.{member} : {}\n```\n\n{note}",
            show_signature(ty)
        );
        if let Some(docs) = self.source(module).and_then(|s| documentation(&s, owner)) {
            let _ = write!(markdown, "\n\n{docs}");
        }
        let _ = write!(markdown, "\n\nfrom `{module}`");
        Some((markdown, (token.start, token.end)))
    }
}

/// What the compiler generated as the companion `member` of a type.
pub(in crate::ide) fn companion_note(member: &str) -> Option<&'static str> {
    Some(match member {
        "url" => {
            "The URL codec generated by `deriving Url`. \
             `Route.print` encodes a page as a URL; `Route.parse` decodes a URL \
             to `Some page`, or `None` when it does not match."
        }
        "schema" => "The schema witness generated by `deriving Schema`.",
        "parse" => "Checks the underlying value against this refined type, returning a `Result`.",
        "value" => "The underlying value of this refined type.",
        "json" => "The JSON codec generated for this refined type by `deriving Schema`.",
        "form" => "The form description generated by `deriving Form`.",
        "table" => "The typed SQL table defined by `sql table`.",
        "api" => {
            "The group of endpoints generated by `deriving HttpApi`, for \
             `HttpApi.add_group`; a group with `Authed` endpoints takes the \
             security scheme, the session tag and the checks first."
        }
        "endpoints" => {
            "The endpoints generated by `deriving HttpApi`, one field per \
             endpoint, for `HttpApi.call` on the client."
        }
        _ => return None,
    })
}

/// The literal the constructor `name` of the enum `def` is, as written.
pub(super) fn enum_literal(def: &TypeDef, name: &str) -> Option<String> {
    let Form::Adt {
        constructors,
        abi: Abi::Literal(literals),
    } = &def.form
    else {
        return None;
    };
    let i = constructors.iter().position(|c| c == name)?;
    Some(match literals.get(i)? {
        EnumLit::String(s) => serde_json::to_string(s).ok()?,
        EnumLit::Int(n) => n.to_string(),
    })
}
