/// Column attributes: their words, what they mean and the attributes they
/// cannot be written with.
const ATTRIBUTES: &[(&str, &str, &[&str])] = &[
    (
        "not null",
        "The column is never NULL: its values are not in `Option`.",
        &["null"],
    ),
    (
        "null",
        "The column may be NULL, as without `not null`: its values are in `Option`.",
        &["not null", "primary key"],
    ),
    (
        "primary key",
        "The primary key of the table; implies `not null`.",
        &["null"],
    ),
    ("unique", "No two rows have the same value.", &[]),
    (
        "default",
        "The database has a default value: an insert may leave the column out.",
        &["generated always", "generated by default"],
    ),
    (
        "generated always",
        "The database computes the value: an insert or update cannot give it.",
        &["default", "generated by default"],
    ),
    (
        "generated by default",
        "The database computes the value unless an insert gives one.",
        &["default", "generated always"],
    ),
];

/// A column's words between `:` and `as`: its type and its attributes.
struct Words {
    ty: Option<(&'static ColumnType, (u32, u32))>,
    attributes: Vec<(usize, (u32, u32))>,
}

fn words(column: &Node, text: &str, dialect: &'static Dialect, before: u32) -> Words {
    let tokens: Vec<Token> = column
        .child_tokens()
        .skip_while(|t| t.kind != K::Colon)
        .skip(1)
        .take_while(|t| t.kind != K::AsKw && t.end <= before)
        .collect();
    let texts: Vec<&str> = tokens.iter().map(|t| t.text(text)).collect();
    let Some(ty) = dialect.column_type(&texts) else {
        return Words {
            ty: None,
            attributes: Vec::new(),
        };
    };
    let mut at = ty.words.split(' ').count();
    let mut attributes = Vec::new();
    while at < texts.len() {
        let found = ATTRIBUTES.iter().position(|(words, ..)| {
            let n = words.split(' ').count();
            texts.len() >= at + n && texts[at..at + n].join(" ") == *words
        });
        let Some(i) = found else {
            at += 1;
            continue;
        };
        let n = ATTRIBUTES[i].0.split(' ').count();
        attributes.push((i, (tokens[at].start, tokens[at + n - 1].end)));
        at += n;
    }
    let n = ty.words.split(' ').count();
    Words {
        ty: Some((ty, (tokens[0].start, tokens[n - 1].end))),
        attributes,
    }
}

/// The row record in the order of the columns.
fn row(info: &SqlTable) -> String {
    let fields = info.columns.iter().map(|c| {
        let ty = if c.nullable {
            Type::app(Type::prim("Option"), c.ty.clone())
        } else {
            c.ty.clone()
        };
        format!("{} : {}", c.name, show_type(&ty))
    });
    format!("{{ {} }}", fields.collect::<Vec<_>>().join("; "))
}

/// The type of `Name$table`, in the order of the columns.
fn table(info: &SqlTable) -> String {
    let columns = info.columns.iter().map(|c| {
        let null = if c.nullable { "Nullable" } else { "NonNull" };
        let ty = show_type(&c.ty);
        format!("{} : Sql.Column {ty} Sql.{null} Sql.{}", c.name, c.write)
    });
    let columns = columns.collect::<Vec<_>>().join("; ");
    format!("Sql.Table \"{}\" {{ {columns} }}", info.table)
}

fn md(code: &str, lang: &str, note: &str) -> String {
    format!("```{lang}\n{code}\n```\n\n{note}")
}

impl Ide<'_> {
    pub(super) fn sql_table_hover(
        &self,
        m: &Analyzed,
        path: &[&Node],
        offset: u32,
    ) -> Option<(String, (u32, u32))> {
        let text = self.text(m.file);
        let dialect = m.typing.sql_dialect;
        let decl = path.iter().rev().find(|n| n.kind == K::SqlTableDecl)?;
        let info = m.typing.sql_tables.iter().find(|t| t.decl == decl.range());
        let node = path.last()?;
        let token = node
            .child_tokens()
            .find(|t| t.start <= offset && offset < t.end)?;
        if node.kind == K::SqlTableDecl {
            let info = info?;
            let row = format!("type alias {} = {}", info.name, row(info));
            return match token.kind {
                K::SqlKw | K::Ident => {
                    let end = decl
                        .child_tokens()
                        .find(|t| t.kind == K::Ident)
                        .map_or(token.end, |t| t.end);
                    let code = format!("{row}\n{}$table : {}", info.name, table(info));
                    let doc = format!(
                        "Declares the row type `{0}` and the table `{0}$table`, which \
                         queries name `{0}`: `from row in {0}`. Dialect: {1}.",
                        info.name, dialect.title
                    );
                    Some((md(&code, "flick", &doc), (decl.range().0, end)))
                }
                K::Con => {
                    let doc = format!(
                        "A row of the {} table `{}`; in a query `{}` names the table.",
                        dialect.title, info.table, info.name
                    );
                    Some((md(&row, "flick", &doc), (token.start, token.end)))
                }
                K::String => {
                    let doc = format!(
                        "The table's name in the database: queries over `{}` read and write `{}`.",
                        info.name, info.table
                    );
                    Some((md(&info.table, "sql", &doc), (token.start, token.end)))
                }
                _ => None,
            };
        }
        if node.kind != K::SqlColumn {
            return None;
        }
        let words = words(node, text, dialect, u32::MAX);
        if let Some((ty, range)) = words.ty
            && range.0 <= offset
            && offset < range.1
        {
            let doc = format!(
                "{} `{}`: Flick value `{}` (before a `via` codec).",
                dialect.title, ty.words, ty.flick
            );
            return Some((md(ty.words, "sql", &doc), range));
        }
        if let Some((i, range)) = words
            .attributes
            .iter()
            .find(|(_, r)| r.0 <= offset && offset < r.1)
        {
            let (words, doc, _) = ATTRIBUTES[*i];
            return Some((md(words, "sql", doc), *range));
        }
        let column = info.and_then(|info| {
            let name = node.child_tokens().find(|t| t.kind == K::Ident)?;
            info.columns.iter().find(|c| c.name == name.text(text))
        });
        let shown = column.map_or_else(|| "T".to_owned(), |c| show_type(&c.ty));
        let doc = match (token.kind, token.text(text)) {
            (K::AsKw, _) => format!(
                "The Flick type `{shown}` of the column's values; without `via` it is the \
                 type the SQL type gives."
            ),
            (K::Ident, "via") => {
                let base = column.map_or("…", |c| dialect.flick_type(&c.kind));
                format!("A `PureCodec {base} {shown}` between the SQL value and `{shown}`.")
            }
            _ => return None,
        };
        Some((
            md(token.text(text), "flick", &doc),
            (token.start, token.end),
        ))
    }

    /// Completions in a column of a `sql table`.
    pub(super) fn sql_table_complete(
        &self,
        m: &Analyzed,
        column: &Node,
        offset: u32,
    ) -> Vec<Completion> {
        let text = self.text(m.file);
        let dialect = m.typing.sql_dialect;
        let before: Vec<Token> = column
            .child_tokens()
            .take_while(|t| t.end <= offset)
            .collect();
        if before
            .iter()
            .any(|t| t.kind == K::Ident && t.text(text) == "via")
        {
            return self.codecs(m, column, offset);
        }
        if before.iter().any(|t| t.kind == K::AsKw) {
            let names = self.complete_names(m.file, offset);
            return names
                .into_iter()
                .filter(|c| matches!(c.kind, CompletionKind::Type | CompletionKind::Module))
                .collect();
        }
        if !before.iter().any(|t| t.kind == K::Colon) {
            return Vec::new();
        }
        let words = words(column, text, dialect, offset);
        if words.ty.is_none() {
            return dialect
                .types
                .iter()
                .map(|t| item(t.words, CompletionKind::Type, Some(t.flick.to_owned())))
                .collect();
        }
        let present: Vec<&str> = words
            .attributes
            .iter()
            .map(|(i, _)| ATTRIBUTES[*i].0)
            .collect();
        let mut out: Vec<Completion> = ATTRIBUTES
            .iter()
            .filter(|(w, _, conflicts)| {
                !present.contains(w) && !conflicts.iter().any(|c| present.contains(c))
            })
            .map(|(w, doc, _)| item(w, CompletionKind::Keyword, Some((*doc).to_owned())))
            .collect();
        out.push(item(
            "as",
            CompletionKind::Keyword,
            Some("The Flick type of the column".to_owned()),
        ));
        out
    }

    /// Values in scope, unqualified or through an import, whose type
    /// instantiates to a codec between the column's SQL value and its type.
    fn codecs(&self, m: &Analyzed, column: &Node, offset: u32) -> Vec<Completion> {
        let text = self.text(m.file);
        let words: Vec<&str> = column
            .child_tokens()
            .skip_while(|t| t.kind != K::Colon)
            .skip(1)
            .map(|t| t.text(text))
            .collect();
        let Some(sql) = m.typing.sql_dialect.column_type(&words) else {
            return Vec::new();
        };
        let Some(ty) = checked_type(&m.typing.sql_tables, column, text)
            .filter(|t| !t.contains(&mut |t| *t == Type::Error))
        else {
            return Vec::new();
        };
        let target = Type::apps(
            Type::prim("PureCodec"),
            [base_type(m.typing.sql_dialect, sql.kind), ty],
        );
        let mut candidates: BTreeMap<String, Type> = BTreeMap::new();
        let mut interfaces = vec![m.interface.clone()];
        interfaces.extend(self.interface(PRELUDE));
        for import in m.tree.nodes().filter(|n| n.kind == K::ImportDecl) {
            let Some(path) = import.nodes().find(|n| n.kind == K::ModulePath) else {
                continue;
            };
            let module: String = path.text(text).split_whitespace().collect();
            let Some(interface) = self.interface(&module) else {
                continue;
            };
            let qualifier = import
                .child_tokens()
                .skip_while(|t| t.kind != K::AsKw)
                .find(|t| t.kind == K::Con)
                .map_or(module, |t| t.text(text).to_owned());
            for (name, scheme) in values(&interface) {
                candidates.insert(format!("{qualifier}.{name}"), scheme.clone());
            }
            interfaces.push(interface);
        }
        // the module's own values, exported or not, with the types the checker gave them
        for d in declarations(&m.tree, text, m.file) {
            if d.namespace == Namespace::Value
                && let Some(ty) = m.typing.types.get(&(d.span.start, d.span.end))
            {
                candidates.insert(d.name, ty.clone());
            }
        }
        // the names in scope unqualified, with the type of their export
        for c in self.complete_names(m.file, offset) {
            if c.kind != CompletionKind::Value {
                continue;
            }
            if let Some((_, scheme)) = interfaces
                .iter()
                .flat_map(values)
                .find(|(name, _)| *name == c.label)
            {
                candidates.insert(c.label, scheme.clone());
            }
        }
        let target = self.expand(m, &target, 0);
        candidates
            .into_iter()
            .filter(|(_, scheme)| {
                let body = match scheme {
                    Type::Forall { body, .. } => body,
                    other => other,
                };
                match_type(&self.expand(m, body, 0), &target, &mut Vec::new()) == Match::Yes
            })
            .map(|(label, scheme)| item(&label, CompletionKind::Value, Some(show_type(&scheme))))
            .collect()
    }
}

impl Ide<'_> {
    /// `ty` with its type aliases replaced by their bodies; those of `m`
    /// come from its typing, so private ones expand too.
    fn expand(&self, m: &Analyzed, ty: &Type, depth: u32) -> Type {
        let (head, args) = ty.spine();
        if depth < 8
            && let Type::Con { module, name } = head
            && let Some((params, body)) = if *module == m.name {
                m.typing.aliases.get(name).cloned()
            } else {
                self.interface(module)
                    .and_then(|i| i.find(Namespace::Type, name)?.definition.clone())
                    .and_then(|d| match d.form {
                        Form::Alias { params, body, .. } => Some((params, body)),
                        _ => None,
                    })
            }
            && params.len() == args.len()
        {
            let subst: Vec<(String, Type)> =
                params.into_iter().zip(args.into_iter().cloned()).collect();
            return self.expand(m, &body.substitute(&subst), depth + 1);
        }
        ty.map_children(&mut |t| self.expand(m, t, depth))
    }
}

/// The values an interface exports, with their types.
fn values(interface: &Interface) -> impl Iterator<Item = (&str, &Type)> {
    interface.exports.iter().filter_map(|e| {
        let named = e.entity.namespace == Namespace::Value && !e.entity.name.contains('$');
        Some((e.entity.name.as_str(), e.scheme.as_ref().filter(|_| named)?))
    })
}

/// The Flick type the checker gave a column.
fn checked_type(tables: &[SqlTable], column: &Node, text: &str) -> Option<Type> {
    let name = column.child_tokens().find(|t| t.kind == K::Ident)?;
    let (start, end) = column.range();
    tables
        .iter()
        .filter(|t| t.decl.0 <= start && end <= t.decl.1)
        .flat_map(|t| &t.columns)
        .find(|c| c.name == name.text(text))
        .map(|c| c.ty.clone())
}
