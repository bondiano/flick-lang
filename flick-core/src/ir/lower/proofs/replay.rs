//! A proof module's proofs as a Lean replay (`just formal-proofs`): the
//! definitions they unfold, each statement and its certificate, in `λPT`.

use super::{Modules, Run, lower_proofs, paired, statement};
use crate::logic;
use crate::resolve;
use crate::types::{GoalType, Typing};

/// The Lean source replaying the proofs of `module`, which checked without
/// errors. A bundle or a law is no proof to replay.
pub fn lean_replay(
    module: &resolve::Module,
    typing: &Typing,
    run: &Run,
    header: &str,
    namespace: &str,
) -> Result<String, String> {
    let proofs = paired(lower_proofs(module, typing), &typing.proofs);
    let own = super::super::lower(module, typing).ok();
    let program = Modules {
        own: own.as_ref(),
        project: run.project,
        builtins: (run.builtins)(),
    };
    let mut lemmas = Vec::new();
    let mut items = Vec::new();
    let mut data = logic::Data::new();
    for (lowered, info) in &proofs {
        if info.class.is_some() || matches!(info.goal, GoalType::Lawful(_)) {
            continue;
        }
        let fail =
            |f: logic::Failure| format!("`{}`: {}", info.name, f.diagnostic(&info.name).message);
        let s = statement(lowered, info).map_err(fail)?;
        let body = lowered
            .body
            .as_ref()
            .ok_or_else(|| format!("`{}` has no proof", info.name))?;
        let cert = logic::cert(body, &lemmas).map_err(fail)?;
        data.extend(&info.data);
        lemmas.push(logic::Lemma {
            statement: s.clone(),
            order: (lowered.params.iter())
                .zip(&lowered.premise)
                .map(|(x, p)| (x.as_str().into(), *p))
                .collect(),
        });
        items.push((s, cert));
    }
    let mut terms = Vec::new();
    for (s, c) in &items {
        for (_, eq) in &s.premises {
            terms.extend([&eq.left, &eq.right]);
        }
        if let logic::Goal::Equal(eq) = &s.goal {
            terms.extend([&eq.left, &eq.right]);
        }
        c.terms(&mut terms);
    }
    let Some(span) = items.first().map(|(s, _)| s.span) else {
        return Err("the module has no proof to replay".into());
    };
    let admitted = logic::admit(&terms, &program, span).map_err(|r| r.why)?;
    logic::lean::lean_replay(header, namespace, admitted.defs(), &items, &data)
}

#[cfg(test)]
mod tests {
    use std::path::Path;
    use std::{env, fs};

    use super::{Run, lean_replay};
    use crate::project::builtins::{builtin_laws, builtin_modules_of};
    use crate::types;

    const HEADER: &str = "/-! Generated by `just formal-proofs` from \
        `packages/core/proofs/Laws/Option.fl`: DO NOT EDIT.\n\n\
        The laws of the instances of `Option`, as the compiler's kernel proved them,\n\
        checked again by the checker `check_sound` proves sound. -/";

    /// The replay of core's `Option` laws is what the proofs and the
    /// definitions in the core give: `just formal-proofs` writes it, and a
    /// change to either fails this until it is written again.
    #[test]
    fn the_option_laws_replay_in_lean() {
        use std::collections::HashSet;
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let laws =
            fs::read_to_string(root.join("packages/core/proofs/Laws/Option.fl")).expect("the laws");
        let mut sources = types::builtin_sources().to_vec();
        sources.push(("Laws.Option", laws.as_str()));
        let no_contracts = HashSet::new();
        let run = Run {
            builtins: &|| builtin_modules_of(false),
            builtin_laws: &|| builtin_laws(false),
            project: &|_| None,
            proven: &|_| None,
            all_contracted: &no_contracts,
            contracts: &|_| &[],
        };
        let mut replay = None;
        types::check_each(&sources, false, |module, typing| {
            if module.name == "Laws.Option" {
                replay = Some(lean_replay(
                    module,
                    typing,
                    &run,
                    HEADER,
                    "Flick.PT.Gen.Option",
                ));
            }
        });
        let replay = replay.expect("the laws module").expect("the laws replay");
        let path = root.join("formal/FormalCert/Gen/Proofs.lean");
        if env::var_os("FLICK_FORMAL_PROOFS").is_some() {
            fs::write(&path, &replay).expect("write the replay");
        } else {
            let kept = fs::read_to_string(&path).unwrap_or_default();
            assert!(
                kept == replay,
                "{} is stale: run `just formal-proofs`",
                path.display()
            );
        }
    }
}
