//! Lean certificates of the programs of the generator
//! (`docs/formal/certificates.md`): the model checks a program, and
//! `flick_model::cert` writes its typing as a proof `lake build` checks.
//! `formal/FormalCert/GenSig.lean` and the golden certificates of
//! `formal/FormalCert/Gen/Golden.lean` are what the model writes (`just
//! formal-certs`); the forms the certificates do not write yet, over a fixed
//! run of programs, are `cert_gaps.txt`, and the list may only shrink.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::{env, fs};

use flick_model::cert::{certificate, sig::Sig};
use flick_model::check::Checker;
use flick_model::decls::Decls;
use flick_model::generate::{self, Program};
use flick_model::run;

/// How many certificates `Golden.lean` has.
const GOLDEN: usize = 32;

fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..")
}

fn decls() -> Decls {
    let file = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/generate/Gen.fl");
    let modules = run::compile(&file).expect("Gen.fl compiles");
    run::decls(&modules)
}

/// The programs of a fixed run: choices of a xorshift from one seed.
fn programs(n: usize) -> impl Iterator<Item = (usize, Program)> {
    let mut x: u64 = 0x2545_f491_4f6c_dd1d;
    let mut next = move || {
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        u32::try_from(x >> 32).expect("32 bits")
    };
    (0..n).map(move |i| {
        let len = next() % 80;
        let choices: Vec<u32> = (0..len).map(|_| next()).collect();
        (i, generate::program(&choices))
    })
}

/// The certificate of `p`, or why it has none.
fn certify(decls: &Decls, sig: &Sig, name: &str, p: &Program) -> Result<String, String> {
    let trace = Checker::new(decls)
        .check_top_traced(&p.term, &p.scheme)
        .map_err(|_| "the model rejects it".to_owned())?;
    certificate(name, p, &trace, sig)
}

/// The source of `p` as a comment above its certificate.
fn comment(p: &Program) -> String {
    let source = generate::source(p);
    let program = source.split("\nprogram :").nth(1).unwrap_or("");
    format!(
        "-- program :{}\n",
        program.trim_end().replace('\n', "\n-- ")
    )
}

fn file(header: &str, body: &str) -> String {
    format!(
        "-- Code generated by `just formal-certs`. DO NOT EDIT.\n\nimport FormalCert.GenSig\n\n{header}\
         namespace Flick.Cert.Golden\n\nopen Flick Flick.Cert\n\n{body}end Flick.Cert.Golden\n"
    )
}

/// `text` is the file at `path` of the repository; with
/// `FLICK_FORMAL_CERTS` set it becomes so.
fn fresh(path: &str, text: &str) {
    let path = repo().join(path);
    if env::var_os("FLICK_FORMAL_CERTS").is_some() {
        fs::create_dir_all(path.parent().expect("a directory")).expect("a directory");
        fs::write(&path, text).expect("write");
    }
    let committed = fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == text,
        "{} is stale: run `just formal-certs`",
        path.display()
    );
}

#[test]
fn the_certificates_are_fresh() {
    let decls = decls();
    let sig = Sig::of(&decls);
    fresh("formal/FormalCert/GenSig.lean", &sig.lean());
    let mut body = String::new();
    let mut count = 0;
    for (i, p) in programs(4000) {
        if count == GOLDEN {
            break;
        }
        if let Ok(cert) = certify(&decls, &sig, &format!("program{i}"), &p) {
            body.push_str(&comment(&p));
            body.push_str(&cert);
            body.push('\n');
            count += 1;
        }
    }
    assert_eq!(count, GOLDEN, "too few programs have a certificate");
    let header = "/-!\n# Golden certificates\n\nThe first programs of a fixed run of the model's generator that have a certificate\n\
                  (`flick-model/tests/certs.rs`), each above its typing in the core.\n-/\n\n";
    fresh("formal/FormalCert/Gen/Golden.lean", &file(header, &body));
}

/// `reason -> count` of `cert_gaps.txt`.
fn gaps() -> BTreeMap<String, usize> {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/cert_gaps.txt");
    fs::read_to_string(path)
        .unwrap_or_default()
        .lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
        .map(|l| {
            let (n, reason) = l.split_once(' ').expect("`<count> <reason>`");
            (reason.to_owned(), n.parse().expect("a count"))
        })
        .collect()
}

/// The forms a fixed run of programs needs and the certificates do not
/// write: exactly `cert_gaps.txt`, so a new gap fails and a closed one is
/// taken off the list. The certificates go to `target/certs/Batch.lean`,
/// which `just model-certs` checks with Lean.
#[test]
#[ignore = "certifies a run of generated programs; run `just model-certs`"]
fn certificates_of_generated_programs() {
    let n = env::var("CERT_PROGRAMS")
        .ok()
        .and_then(|n| n.parse().ok())
        .unwrap_or(500);
    let decls = decls();
    let sig = Sig::of(&decls);
    let mut body = String::new();
    let mut reasons: BTreeMap<String, usize> = BTreeMap::new();
    let mut certified = 0;
    for (i, p) in programs(n) {
        match certify(&decls, &sig, &format!("program{i}"), &p) {
            Ok(cert) => {
                body.push_str(&cert);
                body.push('\n');
                certified += 1;
            }
            Err(why) => *reasons.entry(why).or_default() += 1,
        }
    }
    let dir = repo().join("target/certs");
    fs::create_dir_all(&dir).expect("target/certs");
    fs::write(dir.join("Batch.lean"), file("", &body)).expect("write");
    println!("{certified} of {n} programs have a certificate");
    if n == 500 {
        let listed = gaps();
        let mut lines: Vec<String> = reasons.iter().map(|(r, c)| format!("{c} {r}")).collect();
        lines.sort();
        assert_eq!(
            reasons,
            listed,
            "the gaps changed; `cert_gaps.txt` would be:\n{}",
            lines.join("\n")
        );
    }
}
