//! Lean source emission for `formal/FormalCert/GenSig.lean` (`cert::sig::Sig`).

use std::collections::BTreeMap;
use std::fmt::Write;
use std::rc::Rc;

use super::sig::Sig;
use crate::translate::lean::elide::{Env, Types, scheme_facts};
use crate::types::Scheme;
use crate::variance::Sign;

impl Sig {
    /// `genOps`, `genOp` and `genArity`: the operations of each service and
    /// its number of parameters.
    fn gen_ops(&self, out: &mut String) {
        out.push_str("def genOps : Name → List Name\n");
        for (svc, ops) in &self.ops {
            let names: Vec<String> = ops
                .iter()
                .map(|o| format!("{:?}", o.name.to_string()))
                .collect();
            let _ = writeln!(out, "  | {svc:?} => [{}]", names.join(", "));
        }
        out.push_str("  | _ => []\n\ndef genOp : Name → Name → Option (OpClass × Ty × Ty)\n");
        for (svc, ops) in &self.ops {
            for o in ops {
                let _ = writeln!(
                    out,
                    "  | {svc:?}, {:?} => some (.tail, {}, {})",
                    o.name.to_string(),
                    o.a,
                    o.b
                );
            }
        }
        out.push_str("  | _, _ => none\n\n");
        out.push_str("def genArity : Name → Nat\n");
        for (svc, n) in self.arity.iter().filter(|(_, n)| **n > 0) {
            let _ = writeln!(out, "  | {svc:?} => {n}");
        }
        out.push_str("  | _ => 0\n\n");
    }

    /// `genVar`, `genDictVar`, the variances of the types and classes of the
    /// generator, and the structure with the signature that has them.
    fn gen_var(&self, out: &mut String, max_dict_fields: usize) {
        out.push_str(
            "/-- The variance of each parameter of the generator's data (`flick-model/src/variance.rs`). -/\n\
             def genVar : Name → Nat → Variance\n",
        );
        for (adt, signs) in &self.vars {
            for (j, s) in signs.iter().enumerate() {
                let s = match s {
                    Sign::Pos => ".pos",
                    Sign::Neg => ".neg",
                    Sign::Bi => ".bi",
                    Sign::Inv => continue,
                };
                let _ = writeln!(out, "  | {adt:?}, {j} => {s}");
            }
        }
        out.push_str("  | _, _ => .inv\n\n");
        out.push_str(
            "/-- The variance of each parameter of the generator's classes (`flick-model/src/variance.rs`). -/\n\
             def genDictVar : Nat → Nat → Variance\n",
        );
        for (c, signs) in self.dict_vars.iter().enumerate() {
            for (j, s) in signs.iter().enumerate() {
                let s = match s {
                    Sign::Pos => ".pos",
                    Sign::Neg => ".neg",
                    Sign::Bi => ".bi",
                    Sign::Inv => continue,
                };
                let _ = writeln!(out, "  | {c}, {j} => {s}");
            }
        }
        out.push_str("  | _, _ => .inv\n\n");
        // one case for each index below the most parameters, and the rest
        let most = self.ctors.values().map(|c| c.k).max().unwrap_or(0);
        let most_dict = self.dicts.iter().map(|(k, _)| *k).max().unwrap_or(0);
        let dict_fields = vec!["⟨-, rfl⟩"; max_dict_fields.max(1)].join(" | ");
        out.push_str(
            &WITNESS
                .replace("$CASES", &"_ | ".repeat(most))
                .replace("$DICT_CASES", &"_ | ".repeat(most_dict))
                .replace("$DICT_FIELDS", &dict_fields),
        );
    }

    /// The text of `formal/FormalCert/GenSig.lean`; a global the core
    /// cannot write is left out, with its reason.
    pub fn lean(&self) -> String {
        let mut out = String::from(
            "-- Code generated by `just formal-certs`. DO NOT EDIT.\n\n\
             import FormalCert.Rules\n\n\
             /-!\n\
             # The signature of the generator's programs\n\n\
             The constructors and globals the programs of the model's generator take from `Gen.fl`\n\
             and the Prelude (`flick-model/src/cert/sig.rs`), a global at its elided scheme. A\n\
             certificate assumes `GenSig S`; `GenSig.inhabited` gives a signature that has them.\n\
             -/\n\n\
             namespace Flick.Cert\n\n\
             def genCtor : Name → Option (Nat × List Ty × Name)\n",
        );
        for (name, c) in &self.ctors {
            let _ = writeln!(
                out,
                "  | {name:?} => some ({}, [{}], {:?})",
                c.k,
                c.fields.join(", "),
                c.adt
            );
        }
        out.push_str("  | _ => none\n\n");
        out.push_str(
            "def genRes (K : Name) : List Ty :=\n  match genCtor K with\n  | some (k, _, _) => idTs k\n  | none => []\n\n",
        );
        out.push_str("/-- The constructors of each type, with their arity. -/\ndef genAdtCtors : Name → List (Name × Nat)\n");
        let mut adts: BTreeMap<&str, Vec<String>> = BTreeMap::new();
        for (name, c) in &self.ctors {
            adts.entry(&c.adt)
                .or_default()
                .push(format!("({name:?}, {})", c.fields.len()));
        }
        for (adt, cs) in &adts {
            let _ = writeln!(out, "  | {adt:?} => [{}]", cs.join(", "));
        }
        out.push_str("  | _ => []\n\n");
        out.push_str("def genGlob : Nat → Option Scheme\n");
        let mut skipped = String::new();
        for (i, (key, s)) in self.globs.iter().enumerate() {
            match scheme(s, &self.classes, &self.types) {
                Ok(text) => {
                    let _ = writeln!(out, "  -- {key:?}\n  | {i} => some {text}");
                }
                Err(why) => {
                    let _ = writeln!(skipped, "-- skip {key:?}: {why}");
                }
            }
        }
        out.push_str("  | _ => none\n\n");
        self.gen_ops(&mut out);
        out.push_str("def genDict : Nat → Option (Nat × List (Label × Scheme))\n");
        let mut most = 1;
        for (i, (k, fields)) in self.dicts.iter().enumerate() {
            if fields.is_empty() {
                continue;
            }
            most = most.max(fields.len());
            let fs: Vec<String> = fields
                .iter()
                .map(|(l, s)| format!("({l:?}, {s})"))
                .collect();
            let _ = writeln!(out, "  | {i} => some ({k}, [{}])", fs.join(", "));
        }
        out.push_str("  | _ => none\n\n");
        let each = vec!["⟨-, rfl⟩"; most].join(" | ");
        let _ = write!(
            out,
            "theorem genDict_closed : ∀ c k fs, genDict c = some (k, fs) → ∀ l s, (l, s) ∈ fs →\n    \
             s.Closed (s.k + k) := by\n  intro c k fs h l s hm\n  unfold genDict at h\n  \
             split at h <;> cases h <;>\n    \
             simp only [List.mem_cons, List.mem_nil_iff, or_false, Prod.mk.injEq] at hm <;>\n    \
             rcases hm with {each} <;> subst_vars <;> closed_tac\n\n"
        );
        self.gen_var(&mut out, most);
        if !skipped.is_empty() {
            out.push_str("\n/-! ## Skipped -/\n\n");
            out.push_str(&skipped);
        }
        out
    }
}

/// `⟨k, Facts.none, τ⟩` of a scheme without facts.
fn scheme(s: &Scheme, classes: &[String], types: &Rc<Types>) -> Result<String, String> {
    let env = Env {
        vars: s.vars.iter().map(|(v, _)| v.to_string()).collect(),
        classes: classes.to_vec(),
        types: Some(types.clone()),
        ..Env::default()
    };
    let (cs, t) = scheme_facts(s, &env)?;
    Ok(format!("⟨{}, {cs}, {t}⟩", s.vars.len()))
}

/// The structure, and the signature that has it; `$CASES` is a case for each
/// index below the most parameters of a type.
const WITNESS: &str = include_str!("witness.lean");
